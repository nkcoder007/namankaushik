import type { NextConfig } from "next";

/**
 * Static export for Cloudflare Pages.
 *
 * `output: "export"` writes a fully static site to `out/`: `next build` no
 * longer produces a server, so the deployment target serves the files directly.
 *
 * Two consequences are handled below:
 *
 * 1. Images. Static hosting has no Next.js image optimizer, so `unoptimized`
 *    makes `<Image>` render a plain `<img>` pointing at the original file in
 *    `public/`. The portrait and the mascot artwork are already sized for
 *    their layout slots, so nothing is re-encoded, cropped or scaled — the
 *    rendered pixels, dimensions, aspect ratios and `fill`/`object-cover`
 *    behaviour are unchanged. No external image service is involved.
 *
 * 2. Response headers. `headers()` is a server feature and is rejected during
 *    a static export, because the files it would decorate are served by the
 *    host instead. The same four security headers now live in
 *    `public/_headers`, which Cloudflare Pages honours for every route and
 *    asset, and which is copied verbatim into `out/`. Values are identical:
 *    nosniff, strict-origin-when-cross-origin, DENY framing, and the same
 *    Permissions-Policy. There is still deliberately no Content-Security-Policy
 *    (the theme and reveal gates run as inline scripts in <head>).
 */
const nextConfig: NextConfig = {
  // Emit `out/index.html` and the rest of the site as static files.
  output: "export",

  // No Next.js image optimizer exists on a static host; serve the source files.
  images: { unoptimized: true },

  // No response is generated by Next.js any more, so the framework never gets
  // the chance to advertise itself. Kept as the project's stated intent.
  poweredByHeader: false,

  // Tailwind v4 is compiled by the Turbopack CSS rule below, which applies to
  // the production build as well as dev — there is no separate PostCSS config.
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
